/**
 * Gera um texto aleatório de N palavras a partir do banco de palavras comuns.
 */
export function generateCommonWordsText(
  wordCount: number,
  includePunctuation: boolean = false
): string {
  const result: string[] = [];
  const punctuationMarks = ['.', ',', '?', ':', ';'];

  for (let i = 0; i < wordCount; i++) {
    const randomIndex = Math.floor(Math.random() * COMMON_PORTUGUESE_WORDS.length);
    let word = COMMON_PORTUGUESE_WORDS[randomIndex];

    if (includePunctuation) {
      // Começo de frase com maiúscula
      if (i === 0 || (i > 0 && result[i - 1]?.endsWith('.'))) {
        word = word.charAt(0).toUpperCase() + word.slice(1);
      }
      // Adiciona pontuação aleatória a cada 5 a 8 palavras
      if (i > 0 && i < wordCount - 1 && Math.random() < 0.18) {
        const mark = punctuationMarks[Math.floor(Math.random() * punctuationMarks.length)];
        word += mark;
      }
    }

    result.push(word);
  }

  let text = result.join(' ');
  if (includePunctuation && !text.endsWith('.')) {
    text += '.';
  }

  return text;
}

/**
 * Gera sequência repetida do alfabeto
 */
export function generateAlphabetText(repetitions: number = 3): string {
  const alphabet = 'abcdefghijklmnopqrstuvwxyz';
  return Array(repetitions).fill(alphabet).join(' ');
}

/**
 * Gera sequência de números para treino de teclado numérico
 */
export function generateNumbersText(groupsCount: number = 25): string {
  const groups: string[] = [];
  for (let i = 0; i < groupsCount; i++) {
    const len = Math.floor(Math.random() * 4) + 2;
    let num = '';
    for (let j = 0; j < len; j++) {
      num += Math.floor(Math.random() * 10).toString();
    }
    groups.push(num);
  }
  return groups.join(' ');
}
